// The Zerun template: { name, difficulty, weight, entryRow, exitRow, rows }, the shape TemplateUtil.TEMPLATES
// holds (rows of '#', '=', '.'; entryRow and exitRow are the rows of the floor tile at the entry and the exit).
// The analysis travels next to it so the game can derive headings and the levels without reading the image.

import { toRows } from "../grid/tiles.js";
import { TEMPLATE } from "../config.js";

/** Builds the template object. The entry and exit default to the floor of the lower level. */
export function toTemplate(tiles, layout, options = {}) {
  const floorRow = options.entryRow ?? lowerFloorRow(tiles, layout);
  return {
    name: options.name ?? "map",
    difficulty: options.difficulty ?? TEMPLATE.difficulty,
    weight: options.weight ?? TEMPLATE.weight,
    entryRow: floorRow,
    exitRow: options.exitRow ?? floorRow,
    rows: toRows(tiles),
  };
}

function lowerFloorRow(tiles, layout) {
  for (let row = tiles.rows - 1; row > layout.separatorRow; row -= 1) {
    const kind = tiles.kinds[row][layout.walls.left.col + 1];
    if (kind !== "empty") return row;
  }
  return tiles.rows - 1;
}

/** Serializes the template and the analysis as an ES module. */
export function toModule(template, analysis, source) {
  const rows = template.rows.map((row) => `    ${JSON.stringify(row)},`).join("\n");
  const head = [
    `// Generated by runners-map from ${source}. Edit the image and convert again; do not edit this file.`,
    "export const template = {",
    `  name: ${JSON.stringify(template.name)},`,
    `  difficulty: ${template.difficulty},`,
    `  weight: ${template.weight},`,
    `  entryRow: ${template.entryRow},`,
    `  exitRow: ${template.exitRow},`,
    "  rows: [",
    rows,
    "  ],",
    "};",
    "",
    `export const analysis = ${JSON.stringify(analysis, null, 2)};`,
    "",
  ];
  return head.join("\n");
}
