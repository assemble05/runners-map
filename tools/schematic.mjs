#!/usr/bin/env node
// A track of rooms and corridors (decided 08/11 by the owner) becomes one template module with its findings, the laps
// and the running height. Usage:
//   node tools/schematic.mjs <schematic.json> [--out dir] [--run-height N]
// Writes <out>/<name>.template.js (the module the game loads) and <out>/<name>.report.json. Exit code 1 when a finding
// is an error, 2 on an unreadable schematic or a usage error.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { extname, join, resolve } from "node:path";
import { analyzeTiles, fromRows } from "../src/index.js";
import { ZERUN_LAPS_RULES } from "../src/config.js";
import { schematicRows } from "../src/schematic/rects.js";

const args = process.argv.slice(2);
const flag = (name) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};
const file = args.find((arg, i) => !arg.startsWith("--") && !(i > 0 && args[i - 1].startsWith("--")));
if (!file || extname(file).toLowerCase() !== ".json") {
  console.error("usage: node tools/schematic.mjs <schematic.json> [--out dir] [--run-height N]");
  process.exit(2);
}

let schematic;
let rows;
try {
  schematic = JSON.parse(readFileSync(resolve(file), "utf8"));
  rows = schematicRows(schematic);
} catch (error) {
  console.error(`${file}: ${error.message}`);
  process.exit(2);
}

const name = (flag("--name") ?? rows.name).replace(/[^a-z0-9_-]+/gi, "-").toLowerCase();
const minTiles = flag("--run-height") !== undefined ? Number(flag("--run-height")) : ZERUN_LAPS_RULES.runHeight.minTiles;
const result = analyzeTiles(fromRows(rows.rows), {
  profile: "zerun-laps",
  name,
  rules: { runHeight: { ...ZERUN_LAPS_RULES.runHeight, minTiles, exempt: rows.exempt } },
});
const errors = [...result.validation.errors, ...rows.errors];
const ok = errors.length === 0;
const laps = result.validation.report?.laps ?? null;
const run = result.validation.report?.run ?? null;

const out = resolve(flag("--out") ?? "records/schematics");
mkdirSync(out, { recursive: true });
const analysis = { profile: "zerun-laps", ok, routes: laps?.routes ?? null, splits: laps?.splits?.length ?? 0, run };
const module = [
  `// Generated by runners-map from the schematic ${file.split(/[\\/]/).pop()}. Edit the schematic and generate again; do not edit this file.`,
  "export const template = {",
  `  name: ${JSON.stringify(result.template.name)},`,
  `  difficulty: ${result.template.difficulty},`,
  `  weight: ${result.template.weight},`,
  `  entryRow: ${result.template.entryRow},`,
  `  exitRow: ${result.template.exitRow},`,
  "  rows: [",
  ...result.template.rows.map((row) => `    ${JSON.stringify(row)},`),
  "  ],",
  "};",
  "",
  `export const analysis = ${JSON.stringify(analysis, null, 2)};`,
  "",
].join("\n");
writeFileSync(join(out, `${name}.template.js`), module);
writeFileSync(
  join(out, `${name}.report.json`),
  JSON.stringify({ name, profile: "zerun-laps", ok, errors, warnings: result.validation.warnings, laps, run, width: rows.width, height: rows.height }, null, 2) + "\n",
);

console.log(`schematic ${name}: ${rows.width}x${rows.height} cells, zerun-laps, ${ok ? "ok" : "NOT OK"}`);
if (laps) {
  const through = laps.exact ? `${laps.routes}` : `more than ${laps.routes - 1}`;
  console.log(`  laps through the spawn: ${through}; ways round the whole track: ${laps.network.routes}; splits: ${laps.splits.length} (${laps.splits.filter((split) => split.fits).length} fit the screen)`);
}
if (run) {
  console.log(`  running height ${run.minTiles} tiles: ${run.low} of ${run.floors} floor tiles fall short (lowest ${run.lowest}, median ${run.median}, highest ${run.highest})`);
}
for (const error of errors) console.log(`  ${error.code}: ${error.message}`);
console.log(`  files: ${join(out, `${name}.template.js`)}, ${join(out, `${name}.report.json`)}`);
process.exitCode = ok ? 0 : 1;
